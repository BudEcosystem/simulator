"""Measured prefix reuse: hit share of prompt tokens against retained traffic (IMPLEMENTATION_PLAN
1.9 A1).

The planner used to assume a working set of ``concurrency x sessions x reusable share x prompt`` and
a hit rate that grows linearly with the cache up to it (``PROFILE_REUSE``, ``PROFILE_USES``, both
``[MEASURE]``). Production traces don't look like that. Replayed through an exact LRU
(``spikes/reuse-traces/analyze_reuse.py``):

- **Conversation:** no hot set; hits build over minutes of traffic (prefix reuse p50 114 s, p90 519
  s), and the ceiling is 0.37, not 0.667.
- **Tool and agent:** a ~40K-token hot set (shared system and tool prompts, reused within a second)
  gives half the hits, then a long tail; ceiling 0.57, not 0.90.

A curve maps *retained traffic seconds* ``W = cached tokens / (request rate x mean prompt tokens)``
to the share of prompt tokens served from cache. Normalising by time keeps it portable across GPU
speeds: the gaps it measures are people thinking and tools running, not the engine. Generated by
``analyze_reuse.py --curve``; regenerate, don't edit.
"""

from __future__ import annotations

import bisect
from dataclasses import dataclass
from typing import Dict, Tuple


@dataclass(frozen=True)
class ReuseCurve:
    name: str  # name@version, recorded in the plan's decisions
    source: str
    ceiling: float  # hit share an unbounded cache reaches
    # Median share of a prompt served from cache, over requests that hit at all: the prefix a load
    # replaces, which the break-even compares against recompute.
    reused_prefix_share: float
    # (retained seconds, hit share), seconds ascending from 0
    points: Tuple[Tuple[float, float], ...]
    # Squared coefficient of variation of prompt length (variance / mean^2): how uneven the
    # requests' prefill work is, for the TTFT queueing term (``predict.py``). 1.0 is an exponential
    # spread.
    prompt_cv2: float = 1.0
    # Arrivals' burstiness: requests per second, variance over mean (1.0 is Poisson), for the same
    # term (Kingman's G/G/1 approximation).
    arrival_cv2: float = 1.0
    # The trace's requests per second. A deployment that sees a fraction p of that rate sees
    # burstiness 1 + p (arrival_cv2 - 1), a random thinning of the trace's stream. 0: not scaled.
    arrival_rate: float = 0.0

    def hit(self, seconds: float) -> float:
        """Share of prompt tokens a cache of ``seconds`` of traffic serves (piecewise linear)."""
        if seconds <= 0:
            return 0.0
        xs = [p[0] for p in self.points]
        i = bisect.bisect_right(xs, seconds)
        if i >= len(self.points):
            return self.points[-1][1]
        (x0, y0), (x1, y1) = self.points[i - 1], self.points[i]
        return y0 + (y1 - y0) * (seconds - x0) / (x1 - x0)

    def seconds_for(self, fraction: float) -> float:
        """Smallest retained seconds reaching ``fraction`` of the ceiling."""
        target = fraction * self.ceiling
        for (x0, y0), (x1, y1) in zip(self.points, self.points[1:]):
            if y1 >= target:
                return x0 if y1 == y0 else x0 + (x1 - x0) * (target - y0) / (y1 - y0)
        return self.points[-1][0]


